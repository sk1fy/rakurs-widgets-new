export async function sessionRefreshChecks(browser, base, check) {
  for (const mode of ["external", "profile"]) {
    const page = await browser.newPage();
    await page.clock.install();
    const text = (id) => page.getByTestId(id).innerText();
    const wait = (id, value) => page.getByTestId(id).filter({ hasText: value }).waitFor();
    const click = (name) => page.getByRole("button", { name, exact: true }).click();
    await page.goto(`${base}e2e/session-refresh.html?mode=${mode}`);
    await wait("requests", "1");
    await click("Resolve latest");
    await wait("data", "source1-employee7-request1");
    await click("Hide tab");
    await page.clock.fastForward(2400000);
    check(await text("requests") === "1", `${mode}: hidden sessions do not poll`);
    await click("Show tab");
    await click("Focus");
    await wait("requests", "2");
    check(await text("data") === "source1-employee7-request1", `${mode}: return refresh retains displayed intervals`);
    await click("Reject latest");
    await wait("error", "failed");
    check(await text("data") === "source1-employee7-request1", `${mode}: refresh failure retains old intervals with an error`);
    await page.clock.fastForward(240000);
    await wait("requests", "3");
    await click("Resolve latest");
    await wait("data", "source1-employee7-request3");
    check(await text("error") === "none", `${mode}: four-minute retry replaces data and clears the error`);
    await page.clock.fastForward(240000);
    await wait("requests", "4");
    await page.clock.fastForward(480000);
    check(await text("requests") === "4", `${mode}: slow session refresh is not restarted`);
    await click("Change employee");
    await wait("requests", "5");
    check(await text("data") === "empty", `${mode}: changing employee clears the old scope`);
    await click("Resolve latest");
    await wait("data", "source1-employee8-request5");
    await click("Resolve oldest");
    check(await text("data") === "source1-employee8-request5", `${mode}: late old employee response cannot overwrite current intervals`);
    await click("Change source");
    await wait("requests", "6");
    check(await text("data") === "empty", `${mode}: changing source clears previous source data`);
    await click("Resolve latest");
    await wait("data", "source2-employee8-request6");
    await click("Change range");
    await wait("requests", "7");
    check(await text("data") === "empty", `${mode}: changing timezone or range reloads the session scope`);
    await click("Resolve latest");
    await wait("data", "source2-employee8-request7");
    await page.close();
    const hidden = await browser.newPage();
    await hidden.clock.install();
    await hidden.goto(`${base}e2e/session-refresh.html?mode=${mode}&hidden`);
    await hidden.getByRole("button", { name: "Show tab", exact: true }).waitFor();
    await hidden.clock.fastForward(240000);
    check(await hidden.getByTestId("requests").innerText() === "0", `${mode}: initially hidden sessions wait for activation`);
    await hidden.getByRole("button", { name: "Show tab", exact: true }).click();
    await hidden.getByTestId("requests").filter({ hasText: "1" }).waitFor();
    await hidden.close();
    const historical = await browser.newPage();
    await historical.clock.install();
    await historical.goto(`${base}e2e/session-refresh.html?mode=${mode}&historical`);
    await historical.getByTestId("requests").filter({ hasText: "1" }).waitFor();
    await historical.getByRole("button", { name: "Resolve latest", exact: true }).click();
    await historical.getByTestId("data").filter({ hasText: "request1" }).waitFor();
    await historical.clock.fastForward(2400000);
    check(await historical.getByTestId("requests").innerText() === "1", `${mode}: historical sessions do not poll`);
    await historical.close();
  }
}
